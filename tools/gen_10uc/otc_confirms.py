"""Generate OTC FX forward confirmations (PDF) from docs/test/10uc_universe.json. Deterministic."""
import json, pathlib
from decimal import Decimal
from fpdf import FPDF
from pypdf import PdfReader

ROOT = pathlib.Path(__file__).resolve().parents[2]
U = json.loads((ROOT / "docs/test/10uc_universe.json").read_text(encoding="utf-8"))
OUT = ROOT / "tests/v1/fixtures/10uc/otc_confirms"
OUT.mkdir(parents=True, exist_ok=True)
CO = U["company"]["name"]
money = lambda s: f"{Decimal(s):,.2f}"


def make(fx):
    planted = fx["confirmation_status"] == "mismatch"
    rate = fx["confirmation_rate"]
    buy = fx.get("confirmation_buy_amount", fx["buy_amount"])
    ref = "HB" + fx["id"].replace("FXF-", "").replace("-", "")
    pdf = FPDF()
    pdf.set_auto_page_break(False)
    pdf.add_page()
    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 9, fx["counterparty"].replace(" (synthetic)", ""), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 9)
    pdf.cell(0, 5, "Global Markets Operations | Confirmations Desk | confirmations@harbourbank.example (synthetic)", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 13)
    pdf.cell(0, 8, "FX FORWARD TRADE CONFIRMATION", new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    pdf.cell(0, 6, f"Confirmation reference: {ref}    Our ref (client): {fx['id']}", new_x="LMARGIN", new_y="NEXT")
    pdf.cell(0, 6, f"Issued: {fx['trade_date']}    To: {CO} (portfolio {fx['portfolio']})", new_x="LMARGIN", new_y="NEXT")
    pdf.ln(3)
    rows = [
        ("Counterparty", fx["counterparty"]),
        ("Client", CO),
        ("Transaction type", "FX Forward (deliverable)"),
        ("Trade date", fx["trade_date"]),
        ("Value date", fx["value_date"]),
        (f"Client sells ({fx['sell_currency']})", f"{fx['sell_currency']} {money(fx['sell_amount'])}"),
        (f"Client buys ({fx['buy_currency']})", f"{fx['buy_currency']} {money(buy)}"),
        ("Forward rate (USD/SGD)", rate),
        ("Settlement", "Standard settlement instructions on file"),
    ]
    for k, v in rows:
        pdf.set_font("Helvetica", "B", 10); pdf.cell(60, 7, k, border=1)
        pdf.set_font("Helvetica", "", 10); pdf.cell(110, 7, v, border=1, new_x="LMARGIN", new_y="NEXT")
    pdf.ln(5)
    pdf.set_font("Helvetica", "", 9)
    pdf.multi_cell(0, 5, "Please check this confirmation carefully and notify the Confirmations Desk of any discrepancy "
                   "within one business day. In the absence of objection the terms above are deemed agreed. "
                   "This document is synthetic test data and carries no legal effect.")
    pdf.set_y(-20)
    pdf.set_font("Helvetica", "I", 8)
    pdf.cell(0, 5, f"Harbour Bank (synthetic) | {ref} | Page 1 of 1", align="C")
    path = OUT / f"{fx['id']}_confirmation_{fx['trade_date']}.pdf"
    import datetime; pdf.set_creation_date(datetime.datetime(2026, 10, 9, 18, 0, tzinfo=datetime.timezone.utc))
    pdf.output(str(path))
    return path, fx, rate, buy, planted


def verify(path, fx, rate, buy):
    t = " ".join(PdfReader(str(path)).pages[0].extract_text().split())
    for want in (fx["trade_date"], fx["value_date"], money(fx["sell_amount"]), money(buy), rate, fx["counterparty"]):
        assert want in t, (path.name, want)
    assert Decimal(buy) == (Decimal(fx["sell_amount"]) * Decimal(rate)).quantize(Decimal("0.01"))


res = [make(fx) for fx in U["fx_forwards"]]
lines = ["# OTC confirmations manifest", "", "Synthetic. Generated by tools/gen_10uc/otc_confirms.py from docs/test/10uc_universe.json.", "",
         "| File | Holds | Planted facts |", "|---|---|---|"]
for path, fx, rate, buy, planted in res:
    verify(path, fx, rate, buy)
    fact = (f"MISMATCH: confirmation rate {rate} (SGD {money(buy)}) vs trading export {fx['contract_rate']} (SGD {money(fx['buy_amount'])}); "
            f"difference SGD {fx['difference_sgd']}" if planted else "Matches trading export (rate " + rate + ")")
    lines.append(f"| {path.name} | {fx['id']}, {fx['counterparty']}, trade {fx['trade_date']}, value {fx['value_date']}, "
                 f"sell USD {money(fx['sell_amount'])}, buy SGD {money(buy)}, rate {rate} | {fact} |")
(OUT / "MANIFEST.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("ok", [p.name for p, *_ in res])
