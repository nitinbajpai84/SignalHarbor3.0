"""Deterministic trading/OMS export generator. Every figure comes from docs/test/10uc_universe.json.
Synthetic data only. Run: python tools/gen_10uc/trading_export.py"""
import csv, json, datetime as dt
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
U = json.load(open(ROOT / "docs/test/10uc_universe.json", encoding="utf-8"))
OUT = ROOT / "tests/v1/fixtures/10uc/trading_export"
HDR = ["external_trade_id", "trade_date", "settle_date", "portfolio", "side", "instrument_code",
       "instrument_name", "instrument_type", "quantity", "price", "amount", "currency",
       "counterparty", "status", "source_system"]
FIRST, LAST = dt.date(2026, 9, 9), dt.date(2026, 10, 8)  # 30 calendar days to 8 Oct

sec = {s["key"]: s for s in U["securities"]}
rows = []  # (trade_date, row)
for t in U["trades_oct"]:
    if t["security"].startswith("FXF"):
        fx = next(f for f in U["fx_forwards"] if f["id"] == t["security"])
        name, typ, cpty = f"USD/SGD forward to {fx['value_date']}", "fx_forward", fx["counterparty"]
        code = t["security"]
    else:
        s = sec[t["security"]]
        name, typ, cpty = s["canonical_name"], s["instrument_type"], "Synthetic Broker One"
        code = s["identifiers"]["trading_export"]["ticker"]
    rows.append((t["trade_date"], [t["id"], t["trade_date"], t["settlement_date"], t["portfolio"], t["side"],
        code, name, typ, t["quantity"], t["price"], t["amount"], t["currency"], cpty, "executed", "OMS-SYN"]))
# FXF-001 (trade date 15 Sep) is in the window but absent from trades_oct; built from fx_forwards.
f1 = next(f for f in U["fx_forwards"] if f["id"] == "FXF-2026-001")
rows.append((f1["trade_date"], ["T-20260915-F01", f1["trade_date"], f1["value_date"], f1["portfolio"],
    "sell USD / buy SGD", f1["id"], "USD/SGD forward to " + f1["value_date"], "fx_forward",
    f1["sell_amount"], f1["contract_rate"], f1["buy_amount"], f1["buy_currency"], f1["counterparty"],
    "executed", "OMS-SYN"]))

OUT.mkdir(parents=True, exist_ok=True)
for p in OUT.glob("trading_export_*.csv"): p.unlink()
d, files = FIRST, []
while d <= LAST:
    if d.weekday() < 5:
        day = [r for td, r in rows if td == d.isoformat()]
        fn = OUT / f"trading_export_{d:%Y%m%d}.csv"
        with open(fn, "w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh); w.writerow(HDR); w.writerows(day)
        files.append((fn.name, len(day), [r[0] for r in day]))
    d += dt.timedelta(days=1)

note = {"T-20261002-003": "P28 quantity mismatch (export 12000, administrator 10200)",
        "T-20261006-005": "P29 missing at administrator",
        "T-20261005-004": "P30 FX forward confirmation rate mismatch (export 1.3425, confirmation 1.3452)",
        "T-20260915-F01": "FXF-2026-001, confirmation matched (1.3400)",
        "T-20261001-001": "P31 matched", "T-20261002-002": "P31 matched", "T-20261007-006": "P31 matched"}
md = ["# Trading export fixtures (synthetic)", "",
      "Daily OMS trade export for Evergreen Office (fictional), business days 9 Sep to 8 Oct 2026. "
      "Generated by tools/gen_10uc/trading_export.py from docs/test/10uc_universe.json. Header-only files are days with no trades.", "",
      "Columns: " + ", ".join(HDR), "", "| File | Trades | Ids | Planted facts |", "|---|---|---|---|"]
for fn, n, ids in files:
    md.append(f"| {fn} | {n} | {', '.join(ids) or '-'} | {'; '.join(note[i] for i in ids) or '-'} |")
md += ["", f"Total: {len(files)} files, {sum(n for _, n, _ in files)} trades (7 including 2 FX forwards).", "",
       "Note: FXF-2026-001 has no row in universe trades_oct; its row (id T-20260915-F01, a derived id) uses the fx_forwards figures."]

# cash movements booked by the trading desk (P08b: WIRE-20261008-B01 on 8 Oct; the administrator books it on 9 Oct)
CASH_HDR = ["value_date", "reference", "legal_entity", "portfolio", "movement_type", "description", "counterparty", "amount", "currency", "source_system"]
CASH_FILE = OUT / "cash_movements_trading_export_2026-09-09_to_2026-10-08.csv"
pf_of = {c["legal_entity"]: c["portfolio"] for c in U["cash_8_oct"]}
moves = sorted((t for t in U["cash_activity"] if t["trading_export_date"]), key=lambda t: (t["trading_export_date"], t["entity"], t["reference"]))
with open(CASH_FILE, "w", newline="", encoding="utf-8") as fh:
    w = csv.writer(fh); w.writerow(CASH_HDR)
    w.writerows([t["trading_export_date"], t["reference"], t["entity"], pf_of[t["entity"]], t["movement_type"], t["description"], t["counterparty"],
                 t["amount"], t["currency"], "OMS-SYN"] for t in moves)
md += ["", f"`{CASH_FILE.name}`: {len(moves)} cash movements booked by the trading desk, 9 Sep to 8 Oct 2026, from universe `cash_activity` (trading_export_date). "
       "From the 8 Sep closing balances (`cash_opening_8_sep`) they add up to the trading-export cash of every day. "
       "P08b: WIRE-20261008-B01, -12,400.00 (legal fees) booked here on 8 Oct, by the administrator on 9 Oct. CHG-20261006-T01, -1,800.00, the Trust's charge, booked here only."]
(OUT / "MANIFEST.md").write_text("\n".join(md) + "\n", encoding="utf-8")

# verify by re-reading
got = {}
for fn, _, _ in files:
    for r in csv.DictReader(open(OUT / fn, encoding="utf-8")): got[r["external_trade_id"]] = r
for t in U["trades_oct"]:
    r = got[t["id"]]
    assert (r["quantity"], r["price"], r["amount"], r["currency"], r["trade_date"], r["settle_date"], r["side"]) == \
           (t["quantity"], t["price"], t["amount"], t["currency"], t["trade_date"], t["settlement_date"], t["side"]), t["id"]
r = got["T-20260915-F01"]; assert (r["quantity"], r["price"], r["amount"]) == (f1["sell_amount"], f1["contract_rate"], f1["buy_amount"])
assert len(got) == 7
bal = {(c["entity"], c["date"]): Decimal(c["trading_export"]) for c in U["cash_daily"]}
cm = list(csv.DictReader(open(CASH_FILE, encoding="utf-8")))
for (ent, day), want in bal.items():
    assert Decimal(U["cash_opening_8_sep"][ent]["trading_export"]) + sum(Decimal(r["amount"]) for r in cm if r["legal_entity"] == ent and r["value_date"] <= day) == want, (ent, day)
print(len(files), "files,", len(got), "trades, verified")
