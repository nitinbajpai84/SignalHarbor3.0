/** "Friday 9 October" from a date such as 2026-10-09 (the time zone cannot move a date that has no time). */
export const dateWords = (iso: string | null | undefined, short = false): string =>
  iso ? new Date(`${iso}T12:00:00`).toLocaleDateString("en-GB", short ? { day: "numeric", month: "short" } : { weekday: "long", day: "numeric", month: "long" }) : "";
export const clockText = (s: number): string => `${Math.floor(s / 60)}:${String(Math.floor(s % 60)).padStart(2, "0")}`;

