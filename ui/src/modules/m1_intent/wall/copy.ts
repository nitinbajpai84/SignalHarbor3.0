/** "Fri 17:00" for the header; the stage bar spells the day out. Null when the server sent no usable time. */
export function closesWhen(iso: string | null | undefined, weekday: "short" | "long" = "short"): string | null {
  if (!iso || Number.isNaN(Date.parse(iso))) return null;
  return new Date(iso).toLocaleString("en-GB", { weekday, hour: "2-digit", minute: "2-digit" });
}
